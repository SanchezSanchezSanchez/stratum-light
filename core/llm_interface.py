class HelperLLMInterface(ABC):
    """
    Abstract Base Class for a helper LLM used in advanced prompt injection detection.
    This interface allows for different backends (local models, remote APIs)
    to be used for analyzing the behavior of a target LLM.
    """

    @abstractmethod
    def __init__(self, config: Dict[str, Any]):
        """
        Initialize the helper LLM adapter with its specific configuration.
        Config might include model paths, API endpoints, keys, etc.
        """
        self.config = config
        logger.info(f"Initializing helper LLM adapter: {self.__class__.__name__}")

    @abstractmethod
    def get_target_model_output(self, model_name: str, prompt: str, api_key: Optional[str] = None, api_endpoint: Optional[str] = None) -> str:
        """
        Generates output from the target LLM (the model being tested for vulnerabilities).
        This method is crucial for obtaining the actual responses that the helper LLM will analyze.

        Args:
            model_name (str): Identifier for the target model (e.g., 'gpt-3.5-turbo', path to local model).
            prompt (str): The prompt to send to the target model.
            api_key (Optional[str]): API key for the target model, if applicable.
            api_endpoint (Optional[str]): API endpoint for the target model, if applicable.


        Returns:
            str: The output generated by the target model.

        Raises:
            Exception: If the model output generation fails.
        """
        pass

    @abstractmethod
    def analyze_model_behavior(
        self,
        prompt_to_test: str,
        target_model_output: str,
        auxiliary_prompt_outputs: Optional[List[Dict[str, str]]] = None
    ) -> Dict[str, Any]:
        """
        Analyzes the behavior of a target model based on its output to a specific prompt,
        potentially comparing it against outputs from auxiliary/benign prompts.

        Args:
            prompt_to_test (str): The prompt that was sent to the target model.
            target_model_output (str): The output generated by the target model for 'prompt_to_test'.
            auxiliary_prompt_outputs (Optional[List[Dict[str, str]]]):
                A list of dictionaries, where each dictionary contains:
                {'prompt': str, 'output': str} for benign/auxiliary prompts.
                This allows the helper LLM to compare behaviors. Defaults to None.

        Returns:
            Dict[str, Any]: A dictionary containing the analysis result, typically including:
                - 'is_deviant_behavior': bool (True if behavior seems off or manipulated)
                - 'ignores_instructions': bool (True if primary instructions seem ignored)
                - 'confidence': float (Confidence score of this assessment)
                - 'reasoning': str (Explanation from the helper LLM)
                - 'error': Optional[str] (If any error occurred during helper LLM analysis)
        """
        pass

    def _log_interaction(self, prompt: str, response: Any, success: bool, error: Optional[str] = None):
        """Helper method to log interactions with the LLM (either target or helper)."""
        log_entry = {
            "adapter": self.__class__.__name__,
            "prompt_length": len(prompt),
            "response_type": type(response).__name__,
            "success": success,
        }
        if error:
            log_entry["error"] = error

        logger.debug(f"LLM Interaction: {log_entry}")

