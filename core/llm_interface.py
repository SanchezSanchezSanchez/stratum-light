class RemoteAPILLMAdapter(HelperLLMInterface):
    """
    Adapter for using a remote LLM API as a helper.
    """
    def __init__(self, config: Dict[str, Any]):
        super().__init__(config)
        self.helper_api_endpoint = self.config.get("REMOTE_HELPER_API_ENDPOINT")
        self.helper_api_key = self.config.get("REMOTE_HELPER_API_KEY")
        self.timeout = self.config.get("REMOTE_HELPER_API_TIMEOUT", 30)

        if not self.helper_api_endpoint:
            logger.warning("RemoteAPILLMAdapter initialized without REMOTE_HELPER_API_ENDPOINT. Helper functionality will be simulated.")

    def get_target_model_output(self, model_name: str, prompt: str, api_key: Optional[str] = None, api_endpoint: Optional[str] = None) -> str:
        if not api_endpoint:
            logger.error("RemoteAPILLMAdapter.get_target_model_output: api_endpoint for target model is required.")
            raise ValueError("api_endpoint must be provided for the target model when using RemoteAPILLMAdapter.")

        logger.info(f"RemoteAPILLMAdapter: Getting output for target model '{model_name}' via API: {api_endpoint}.")

        headers = {
            "Content-Type": "application/json",
        }
        if api_key:
            headers["Authorization"] = f"Bearer {api_key}"

        # TODO: Adapt this payload structure for the specific target model API being called.
        payload = {
            "model": model_name,
            "prompt": prompt,
            "max_tokens": 150
        }

        try:
            response = requests.post(api_endpoint, headers=headers, json=payload, timeout=self.timeout)
            response.raise_for_status()

            response_data = response.json()
            target_output = response_data.get("output") or \
                            response_data.get("text") or \
                            (response_data.get("choices") and response_data["choices"][0].get("text")) or \
                            (response_data.get("results") and response_data["results"][0].get("generated_text")) or \
                            json.dumps(response_data)

            self._log_interaction(json.dumps(payload), target_output, True)
            return str(target_output)
        except requests.exceptions.RequestException as e:
            logger.error(f"RemoteAPILLMAdapter: API request to target model {api_endpoint} failed: {e}", exc_info=True)
            self._log_interaction(json.dumps(payload), "", False, str(e))
            # Normalize reason casing for consistent test expectations (e.g., 'Unauthorized')
            if getattr(e, 'response', None) is not None and getattr(e.response, 'status_code', None):
                status_code = e.response.status_code
                reason = getattr(e.response, 'reason', '')
                normalized_reason = (reason.title() if isinstance(reason, str) else reason)
                message = f"{status_code} Client Error: {normalized_reason}" if normalized_reason else str(e)
                raise Exception(f"Failed to get output from target model API {api_endpoint}: {message}") from e
            raise Exception(f"Failed to get output from target model API {api_endpoint}: {e}") from e
        except (KeyError, IndexError, json.JSONDecodeError) as e:
            logger.error(f"RemoteAPILLMAdapter: Error parsing response from target model API {api_endpoint}: {e}", exc_info=True)
            self._log_interaction(json.dumps(payload), response.text, False, f"Parse error: {e}")
            raise Exception(f"Error parsing response from target model API {api_endpoint}: {e}") from e


